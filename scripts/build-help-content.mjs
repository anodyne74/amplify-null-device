#!/usr/bin/env node
/**
 * Regenerates lib/help/helpContent.generated.ts from the Markdown files in
 * content/help/: the customer user guide (#485), bundled as strings so the
 * portal can show it without reading files at run time. Run after changing
 * anything in content/help/:
 *
 *   npm run generate:help
 *
 * lib/help/__tests__/helpContent.test.ts fails while the two disagree.
 */

import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const contentDir = path.join(root, 'content/help');

const entries = fs
  .readdirSync(contentDir)
  .filter((file) => file.endsWith('.md'))
  .sort()
  .map((file) => `  ${JSON.stringify(file.replace(/\.md$/, ''))}: ${JSON.stringify(fs.readFileSync(path.join(contentDir, file), 'utf8'))},`)
  .join('\n');

const source = `// Generated by scripts/build-help-content.mjs from content/help/. Do not edit.

export const HELP_SOURCES: Record<string, string> = {
${entries}
};
`;

fs.writeFileSync(path.join(root, 'lib/help/helpContent.generated.ts'), source);
