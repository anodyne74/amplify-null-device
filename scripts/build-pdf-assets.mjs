#!/usr/bin/env node
/**
 * Regenerates lib/pdf/brandAssets.generated.ts from the files in
 * lib/pdf/assets/: the brand fonts and the header logo, as base64, so jsPDF
 * can use them on the server and in the browser without reading files at run
 * time. Run after changing anything in lib/pdf/assets/:
 *
 *   node scripts/build-pdf-assets.mjs
 *
 * Manrope and JetBrains Mono are Latin subsets (fontTools pyftsubset) of the
 * upstream fonts; Comfortaa Bold is unmodified, since "Comfortaa" is a
 * Reserved Font Name under its licence. Licences sit beside the fonts.
 */

import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const assets = path.join(root, 'lib/pdf/assets');

export const FONT_FILES = [
  'Comfortaa-Bold.ttf',
  'Manrope-Regular.ttf',
  'Manrope-SemiBold.ttf',
  'Manrope-Bold.ttf',
  'JetBrainsMono-Regular.ttf',
  'JetBrainsMono-Bold.ttf',
];

const base64 = (file) => fs.readFileSync(path.join(assets, file)).toString('base64');

const fonts = FONT_FILES.map((file) => `  '${file}': '${base64(`fonts/${file}`)}',`).join('\n');

const source = `// Generated by scripts/build-pdf-assets.mjs from lib/pdf/assets/. Do not edit.
// Fonts: SIL Open Font License 1.1, see lib/pdf/assets/fonts/OFL-*.txt.

export const FONT_BASE64: Record<string, string> = {
${fonts}
};

/** The Null Device logo, white, cropped to the 171x48pt header window, at 4x. */
export const HEADER_LOGO_PNG_BASE64 = '${base64('logo-header.png')}';
`;

fs.writeFileSync(path.join(root, 'lib/pdf/brandAssets.generated.ts'), source);
console.log('Wrote lib/pdf/brandAssets.generated.ts');
